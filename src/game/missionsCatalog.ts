/**
 * Generates 3 deterministic Daily Offline Challenges seeded by local device date (YYYY-MM-DD)
 * without any network connection or external server.
 */
export function getDailyOfflineChallenges(dateStr?: string): MissionDefinition[] {
  const today = dateStr || new Date().toISOString().slice(0, 10);
  let seed = 0;
  for (let i = 0; i < today.length; i++) {
    seed = (seed * 31 + today.charCodeAt(i)) % 100000;
  }

  const vehicles: VehicleId[] = [
    'shahiq',
    'saqr',
    'rahhal',
    'madina',
    'jabal',
    'barq',
    'hafilat',
    'munqidh',
    'badiya',
    'aseel',
  ];
  const weathers: WeatherPreset[] = [
    'clear',
    'mountain_fog',
    'light_rain',
    'heavy_rain',
    'sandstorm',
  ];
  const tods: TimeOfDayPreset[] = ['sunrise', 'morning', 'afternoon', 'sunset', 'night'];

  return [0, 1, 2].map((idx) => {
    const s = seed + idx * 97;
    const veh = vehicles[s % vehicles.length];
    const weather = weathers[(s >> 2) % weathers.length];
    const tod = tods[(s >> 3) % tods.length];
    const startM = 200 + ((s * 170) % 11500);
    const lengthM = 1600 + ((s * 90) % 1200);
    const finishM = Math.min(14850, startM + lengthM);

    return {
      id: `daily_${today}_${idx + 1}`,
      category: 'daily' as GameModeCategory,
      titleAr: `تحدي اليوم المحلي #${idx + 1} (${today})`,
      subtitleAr: `مهمة يومية متجددة محليًا لمسافة ${((finishM - startM) / 1000).toFixed(1)} كم`,
      descriptionAr:
        'تحدٍ يومي يتم توليده محليًا داخل جهازك وفق تاريخ اليوم دون إنترنت مع مكافأة مضاعفة.',
      recommendedVehicleId: veh,
      startDistanceM: startM,
      finishDistanceM: finishM,
      weatherPreset: weather,
      timeOfDayPreset: tod,
      cargoRequiredPct: idx === 1 ? 50 : 0,
      minCargoIntegrityPct: idx === 1 ? 80 : 0,
      hasAiRival: idx === 0,
      aiRivalSpeedMs: 18.8,
      targetTimeSec: Math.round((finishM - startM) / 14.0),
      rewardCoins: 1350 + idx * 250,
      rewardXp: 320 + idx * 60,
    };
  });
}

export function getDriverRankTitleAr(xp: number): {
  level: number;
  rankTitleAr: string;
  nextLevelXp: number;
} {
  const level = Math.max(1, Math.floor(xp / 500) + 1);
  const nextLevelXp = level * 500;
  let rankTitleAr = 'سائق مبتدئ — دروب تعز';
  if (level >= 15) rankTitleAr = 'أسطورة المسالك ودروب اليمن';
  else if (level >= 10) rankTitleAr = 'سيد العقبات والرمال';
  else if (level >= 6) rankTitleAr = 'خبير النقيل والأودية';
  else if (level >= 3) rankTitleAr = 'سائق دروب متمرس';

  return { level, rankTitleAr, nextLevelXp };
}
